import assert from 'node:assert/strict';
import {OnlinePeer, encodeSignal, decodeSignal} from '../js/online-peer.js';
const description = {type:'offer', sdp:'v=0\r\na=test\r\n'};
assert.deepEqual(decodeSignal(encodeSignal(description), 'offer'), description);
assert.throws(() => decodeSignal(encodeSignal(description), 'answer'), /種類/);
assert.throws(() => decodeSignal('broken', 'offer'), /格式/);
assert.throws(() => decodeSignal('KT1.' + btoa(JSON.stringify({version:'old', ...description})), 'offer'), /版本/);
assert.throws(() => decodeSignal('x'.repeat(100001), 'offer'), /過長/);
globalThis.RTCPeerConnection = class { close() {} };
const messages = [], states = [];
const receiver = new OnlinePeer({onMessage:m => messages.push(m), onStatus:s => states.push(s)});
const receiverChannel = {close(){}, readyState:'open', bufferedAmount:0};
receiver.bind(receiverChannel);
const sender = new OnlinePeer({onMessage(){}, onStatus(){}});
const packets = [];
sender.bind({readyState:'open', bufferedAmount:0, close(){}, send:p => packets.push(p)});
const payload = {type:'snapshot', app:'中文🙂'.repeat(30000), revision:1};
assert(sender.send(payload));
assert(packets.length > 20, 'large snapshots are chunked');
for (const data of packets) receiverChannel.onmessage({data});
assert.deepEqual(messages, [payload], 'Unicode survives chunk boundaries');
receiverChannel.onmessage({data:'{}'});
assert.equal(states.at(-1), 'failed', 'malformed packets fail closed');
sender.channel.bufferedAmount = 300000;
sender.send({test:1});
assert(sender.queue.length > 0, 'backpressure queues packets');
sender.channel.bufferedAmount = 0; sender.channel.onbufferedamountlow();
assert.equal(sender.queue.length, 0);
sender.channel.readyState = 'closed';
assert.equal(sender.send({test:2}), false);
console.log('Online signalling validation, chunking, Unicode and backpressure passed.');
