import assert from 'node:assert/strict';
import * as THREE from '../js/vendor/three.module.min.js';
import {newGame} from '../js/game.js';
import {battleBoardData} from '../js/battle3d.js';
import {createTerrainKit} from '../js/terrain3d.js';
const g=newGame({teams:['angels','kommandos'],ai:null});
g.markers=[{kind:'ladder',x:8,y:8,angle:90},{kind:'ladder',x:10,y:8,carriedBy:'test'}];
const before=JSON.stringify(g),data=battleBoardData(g);
assert.equal(data.markers.length,1,'carried equipment must not be drawn on the ground');
assert.equal(data.markers[0].kind,'ladder');
const kit=createTerrainKit(THREE);
const board=kit.buildBoard(data);
board.updateMatrixWorld(true);
const ladder=board.children.at(-1),bounds=new THREE.Box3().setFromObject(ladder);
assert(bounds.max.y>2,'ladder is rendered vertically, not as a communications marker');
assert.equal(JSON.stringify(g),before,'display does not mutate game state');
const empty={board:data.board,terrain:[],deploy:data.deploy};
const deployed=kit.buildBoard({...empty,phase:'deploy'}),combat=kit.buildBoard({...empty,phase:'firefight'});
assert.equal(deployed.children.length-combat.children.length,data.deploy.length,'3D deployment panels only appear during deployment');
const tomb=newGame({teams:['angels','kommandos'],ai:null,map:'tombworld-1'});
assert.equal(tomb.map,'tombworld-1');
assert(battleBoardData(tomb).tombWorld);
assert(kit.buildBoard(battleBoardData(tomb)).children.length>0);
console.log('3D display: ladder geometry, carried markers, phase overlays and immutable state passed.');
